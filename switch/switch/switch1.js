let nomorHari = 3;
// Tulis kode switch statement di sini
switch (nomorHari) {
     case 1:
        console.log("Hari ke-1: Senin");
        break;
     case 2:
        console.log("Hari ke-2: Selasa");
        break;
     case 3:
        console.log("Hari ke-3: Rabu");
        break;
     case 4:
        console.log("Hari ke-4: Kamis");
        break;
     case 5:
        console.log("Hari ke-5: Jumat");
        break;   
     case 6:
        console.log("Hari ke-6: Sabtu");
        break;
     case 7:
        console.log("Hari ke-7: Minggu");
        break;
default:
    console.log("nomor hari tidak ada")
}