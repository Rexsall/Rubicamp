let warna = "Kuning";
// Tulis kode switch statement di sini

switch (warna) {
    case "Merah":
        console.log("Lampu Merah: Hati Hati Berenti");
        break;

    case "Kuning":
        console.log("Lampu Kuning: Hati Hati Bersiap Berenti");
        break;   
     
    case "Hijau":
        console.log("Lampu Hijau: Hati Hati Jalan");
        break;    
default:
    console.log("Lampu Rusak");        
}